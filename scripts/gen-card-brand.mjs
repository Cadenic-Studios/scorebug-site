#!/usr/bin/env node
/**
 * SCOREBUG // INLINE THE CARD PRESS'S FONTS AND ICON
 *
 *   node scripts/gen-card-brand.mjs
 *
 * Reads app/api/card/fonts/*.ttf and app/api/card/brand/icon-128.png and
 * writes app/api/card/brand.ts with each one base64-encoded.
 *
 * WHY: the documented `next/og` pattern is
 * `fetch(new URL('./Inter.ttf', import.meta.url))`, and it cannot be tested
 * locally — Next's edge sandbox answers "not implemented... yet..." for a
 * bundled asset URL in both `next dev` and `next start`, so the route 500s and
 * the only place the pattern could ever be exercised is production. Inlining
 * means dev, start and Vercel all run the same path and the render can be
 * proven before it ships.
 *
 * Re-run after changing a font subset or the icon.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const CARD = resolve(HERE, '..', 'app', 'api', 'card');

const FONTS = [
  ['Anton-400.ttf', 'ANTON_400'],
  ['Oswald-700.ttf', 'OSWALD_700'],
  ['Oswald-500.ttf', 'OSWALD_500'],
  ['Inter-400.ttf', 'INTER_400'],
  ['Inter-600.ttf', 'INTER_600'],
];

const header = `/**
 * SCOREBUG // THE CARD PRESS'S FONTS AND ICON, INLINED
 *
 * AUTO-GENERATED by scorebug-site/scripts/gen-card-brand.mjs — do not edit.
 *
 * These are base64 rather than files fetched at runtime because the
 * \`fetch(new URL('./x.ttf', import.meta.url))\` form that next/og documents
 * cannot be exercised outside production: Next's local edge sandbox does not
 * implement fetching a bundled asset URL, so both \`next dev\` and
 * \`next start\` 500 on this route. Every marketing post embeds this endpoint;
 * the first deploy is the wrong place to discover whether it renders.
 *
 * Inlined, there is no runtime I/O: dev, start and Vercel run one code path.
 * Base64 costs about a third in source and gzips back to roughly the original
 * bytes, and the whole route — these plus the 1,500 Broadcast Shields — stays
 * well inside the edge bundle limit.
 */

/** Base64 to ArrayBuffer, without Buffer (the edge runtime has no Node globals). */
export function bytes(b64: string): ArrayBuffer {
  const bin = atob(b64)
  const out = new Uint8Array(bin.length)
  for (let i = 0; i < bin.length; i += 1) out[i] = bin.charCodeAt(i)
  return out.buffer
}
`;

const parts = [header];
let total = 0;
for (const [file, name] of FONTS) {
  const b64 = (await readFile(join(CARD, 'fonts', file))).toString('base64');
  total += b64.length;
  parts.push(`\n/** ${file} */\nexport const ${name} = '${b64}'\n`);
}
const icon = (await readFile(join(CARD, 'brand', 'icon-128.png'))).toString('base64');
total += icon.length;
parts.push(`\n/** public/app-icon.png at 128px — the same mark the store listing and the site header use. */\nexport const ICON_PNG = '${icon}'\n`);

await writeFile(join(CARD, 'brand.ts'), parts.join(''), 'utf8');
console.log(`wrote app/api/card/brand.ts — ${Math.round(total / 1024)} KB of base64 (${FONTS.length} faces + the icon)`);
